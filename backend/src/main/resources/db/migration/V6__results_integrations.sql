CREATE TABLE integration_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          TIMESTAMP    NOT NULL,
    system_name VARCHAR(30)  NOT NULL,
    operation   VARCHAR(60)  NOT NULL,
    reference   VARCHAR(60),
    success     BOOLEAN      NOT NULL,
    message     VARCHAR(500),
    duration_ms BIGINT       NOT NULL,
    actor       VARCHAR(60)  NOT NULL
);
CREATE INDEX ix_integration_logs_at ON integration_logs (at);

ALTER TABLE study_groups ADD COLUMN course_approved_at TIMESTAMP;
ALTER TABLE study_groups ADD COLUMN course_approved_by VARCHAR(60);

CREATE TABLE course_results (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id           BIGINT      NOT NULL REFERENCES study_groups (id) ON DELETE CASCADE,
    soldier_id         BIGINT      NOT NULL REFERENCES soldiers (id),
    status             VARCHAR(20) NOT NULL,
    exam_grade         INT,
    drop_reason        VARCHAR(255),
    certificate_no     VARCHAR(60),
    certificate_date   DATE,
    certificate_issuer VARCHAR(160),
    recorded_by        VARCHAR(60) NOT NULL,
    updated_at         TIMESTAMP   NOT NULL,
    CONSTRAINT uq_course_result UNIQUE (group_id, soldier_id)
);
