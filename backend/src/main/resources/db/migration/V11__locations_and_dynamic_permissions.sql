-- ---------------------------------------------------------------------------------------------------------
-- 2. Foydalanuvchilarni hududga biriktirish (military_district_id / military_unit_id -> location_id)
-- ---------------------------------------------------------------------------------------------------------
ALTER TABLE app_users ADD COLUMN location_id BIGINT REFERENCES locations (id);

UPDATE app_users u
SET location_id = (SELECT l.id FROM locations l WHERE l.military_unit_id = u.military_unit_id)
WHERE u.military_unit_id IS NOT NULL;

UPDATE app_users u
SET location_id = (SELECT l.id FROM locations l WHERE l.military_district_id = u.military_district_id)
WHERE u.military_unit_id IS NULL AND u.military_district_id IS NOT NULL;

ALTER TABLE app_users DROP COLUMN military_unit_id;
ALTER TABLE app_users DROP COLUMN military_district_id;

-- ---------------------------------------------------------------------------------------------------------
-- 3. Ruxsatlar jadvallari
-- ---------------------------------------------------------------------------------------------------------
CREATE TABLE role_permissions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role       VARCHAR(40) NOT NULL,
    permission VARCHAR(60) NOT NULL,
    CONSTRAINT uq_role_permission UNIQUE (role, permission)
);

CREATE TABLE user_permissions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    permission VARCHAR(60) NOT NULL,
    CONSTRAINT uq_user_permission UNIQUE (user_id, permission)
);

