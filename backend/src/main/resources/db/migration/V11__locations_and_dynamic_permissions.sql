-- 4 rolli, hududga asoslangan va dinamik sozlanadigan ruxsatlar tizimi.
--   1) locations — foydalanuvchini hududga (respublika / okrug / qism) biriktirish uchun yagona daraxt;
--   2) role_permissions — ADMIN va USER rollari uchun tahrirlanadigan ruxsatlar matritsasi;
--   3) user_permissions — foydalanuvchiga shaxsiy (qo'shimcha) ruxsatlar;
--   4) eski 15 ta rolni yangi 4 ta rolga ko'chirish (eski rolning vakolat darajasi bo'yicha).

-- ---------------------------------------------------------------------------------------------------------
-- 1. Hududlar daraxti
-- ---------------------------------------------------------------------------------------------------------
CREATE TABLE locations (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id            BIGINT REFERENCES locations (id),
    level                VARCHAR(20)  NOT NULL,
    name                 VARCHAR(255) NOT NULL,
    code                 VARCHAR(60),
    military_district_id BIGINT REFERENCES military_districts (id),
    military_unit_id     BIGINT REFERENCES military_units (id),
    CONSTRAINT uq_locations_district UNIQUE (military_district_id),
    CONSTRAINT uq_locations_unit UNIQUE (military_unit_id),
    CONSTRAINT ck_locations_level CHECK (
        (level = 'REPUBLIC' AND parent_id IS NULL AND military_district_id IS NULL AND military_unit_id IS NULL)
        OR (level = 'DISTRICT' AND parent_id IS NOT NULL AND military_district_id IS NOT NULL AND military_unit_id IS NULL)
        OR (level = 'UNIT' AND parent_id IS NOT NULL AND military_district_id IS NULL AND military_unit_id IS NOT NULL))
);

CREATE INDEX ix_locations_parent ON locations (parent_id);

